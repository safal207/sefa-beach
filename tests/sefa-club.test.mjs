import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const menu=JSON.parse(fs.readFileSync(new URL('../menu-baseline.json',import.meta.url),'utf8'));
const start=html.indexOf('function clubSelection('), end=html.indexOf('const clubKey=',start);
assert.ok(start>=0&&end>start);
const {clubSelection,clubSummary}=vm.runInNewContext(html.slice(start,end)+'\n({clubSelection,clubSummary})');
test('malformed stored data',()=>{assert.equal(Object.keys(clubSelection(menu,null)).length,0);assert.equal(Object.keys(clubSelection(menu,[])).length,0)});
test('valid saved items',()=>assert.equal(JSON.stringify(clubSelection(menu,{74:2,95:1})),'{"74":2,"95":1}'));
test('unknown items, missing price and invalid qty',()=>assert.equal(Object.keys(clubSelection(menu,{999:1,84:2,74:51,75:-1,76:0,77:1.5,95:"2"})).length,0));
test('prototype keys are excluded',()=>assert.equal(Object.keys(clubSelection(menu,JSON.parse('{"__proto__":1,"constructor":2,"74":1}'))).join(','),'74'));
test('current catalog prices',()=>{const s=clubSummary(menu,{74:2,95:1});assert.equal(s.count,3);assert.equal(s.total,1400)});
test('repricing',()=>assert.equal(clubSummary(menu.map(x=>x.id===74?{...x,price:700}:x),{74:2,95:1}).total,1500));
test('removed item',()=>assert.equal(clubSummary(menu.filter(x=>x.id!==74),{74:2,95:1}).count,1));
test('source not modified',()=>{const raw={74:2,95:1};clubSummary(menu,raw);assert.equal(raw[74],2);assert.equal(raw[95],1)});
test('independent snapshot',()=>{const raw={74:2};assert.notEqual(clubSummary(menu,raw).selection,raw)});
test('all 123 catalog items',()=>{assert.equal(menu.length,123);for(const x of menu)assert.equal(clubSummary(menu,{[x.id]:1}).count,Number.isFinite(x.price)?1:0)});
test('inline script syntax',()=>{for(const m of html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)){if(m[1].trim())new vm.Script(m[1])}});
