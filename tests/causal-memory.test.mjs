import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync(new URL('../revenue-dashboard-local.html',import.meta.url),'utf8');
const start=html.indexOf('function snapshot('),end=html.indexOf('const $=id=>',start);
assert.ok(start>=0&&end>start);
const f=vm.runInNewContext(html.slice(start,end)+'\n({createDecision,applyDecision,compareDecision,replayTrace,migrateTrace,decodeTrace,appendTrace})');
const row={ready:true,month:'2026-09',period:'evening',zone:'terrace',orders:20,revenue:10000,contribution:4000,aov:500};
const after={...row,month:'2026-11',orders:25,revenue:15000,contribution:6500,aov:600},at='2026-12-01T00:00:00Z';
const e=f.createDecision(row,'menu','compare','decision-1',at),ap=f.applyDecision(e,'2026-10-12'),ob=f.compareDecision(ap,after,true);
const s1=f.appendTrace([],[e],at),s2=f.appendTrace(s1.events,[ap],at),s3=f.appendTrace(s2.events,[ob],at);
test('ordered lifecycle',()=>assert.equal(s3.events.map(x=>x.type).join(','),'HYPOTHESIS_CREATED,ACTION_RECORDED,OBSERVATION_RECORDED'));
test('deterministic replay',()=>assert.equal(JSON.stringify(f.replayTrace(s3.events).entries),JSON.stringify([ob])));
test('derived delta',()=>assert.equal(s3.entries[0].after.deltaContributionPerOrder,60));
test('reject reordered events',()=>assert.throws(()=>f.replayTrace([s3.events[1],s3.events[0]])));
test('duplicate ID',()=>assert.throws(()=>f.replayTrace([s1.events[0],{...s1.events[0],seq:2}])));
test('missing predecessor',()=>assert.throws(()=>f.replayTrace([{...s2.events[1],seq:1}])));
test('reject incompatible context',()=>assert.throws(()=>f.replayTrace([...s2.events,{...s3.events[2],payload:{...s3.events[2].payload,after:{...after,zone:'indoor'}}}])));
test('reject hypothesis overwrite',()=>assert.throws(()=>f.appendTrace(s1.events,[{...e,hypothesis:'changed'}],at)));
test('migrate legacy',()=>assert.equal(JSON.stringify(f.migrateTrace([ob]).entries),JSON.stringify([ob])));
test('do not invent timestamps',()=>assert.ok(f.migrateTrace([ob]).events.every(x=>x.recordedAt===null)));
test('reject corrupt legacy',()=>assert.throws(()=>f.migrateTrace([ob,ob])));
test('export/import roundtrip',()=>assert.equal(JSON.stringify(f.decodeTrace({schema:'sefa-causal-memory-v1',events:s3.events}).entries),JSON.stringify([ob])));
test('reject unknown schema',()=>assert.throws(()=>f.decodeTrace({schema:'other'})));
test('prior trace unchanged',()=>{assert.equal(s1.events.length,1);assert.equal(s2.events.length,2)});
test('script syntax',()=>{for(const m of html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi))new vm.Script(m[1])});
